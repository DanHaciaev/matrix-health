  slug, name, category_id, form, purposes, pack, unit_label, short_description, description, usage, warning,
  composition, specs, price, old_price, stock, is_new, is_popular, is_published, sort
)
select
  v.slug,
  v.name,
  c.id,
  'vials',
  v.purposes,
  'Флакон · лиофилизат',
  'за флакон',
  v.short_description,
  v.description,
  case when v.rx
    then 'Рецептурное лекарственное вещество. Порядок применения и дозировку определяет только лечащий врач.'
    else 'Лиофилизат для приготовления раствора. Продаётся для научных и лабораторных исследований. Не является лекарственным средством; любое применение — только по рекомендации врача.'
  end,
  coalesce(v.warning, 'Не является лекарственным средством. Перед применением проконсультируйтесь со специалистом.'),
  v.composition::jsonb,
  jsonb_build_array(
    jsonb_build_object('label', 'Форма выпуска', 'value', 'Лиофилизат во флаконе'),
    jsonb_build_object('label', 'Производитель', 'value', 'SP Laboratory (Великобритания)'),
    jsonb_build_object('label', 'Хранение', 'value', 'Сухой порошок — при −20 °C или +2…+8 °C, в защищённом от света месте. Готовый раствор — при +2…+8 °C.')
  ),
  v.price_eur,
  null,
  0,
  false,
  false,
  true,
  v.sort
from v
join public.categories c on c.slug = 'peptides'
on conflict (slug) do update set
  name              = excluded.name,
  category_id       = excluded.category_id,
  form              = excluded.form,
  purposes          = excluded.purposes,
  short_description = excluded.short_description,
  description       = excluded.description,
  usage             = excluded.usage,
  warning           = excluded.warning,
  composition       = excluded.composition,
  specs             = excluded.specs,
  price             = excluded.price,
  is_published      = true,
  sort              = excluded.sort;

